'use client'

/**
 * 「방금 로그인하고 돌아왔다」 표시.
 *
 * ─────────────────────────────────────────────────────────
 * **왜 필요한가.**
 *
 * 댓글을 쓰려고 로그인하면 브라우저 방문 기록이 이렇게 쌓인다.
 *
 *   목록 → 상세 → 로그인 → 카카오 → (콜백) → 상세
 *
 * 콜백은 `replace` 라 기록에 안 남지만 **카카오는 남는다.** 남의
 * 도메인이라 우리가 지울 수 없다. 그래서 돌아온 화면에서 뒤로가기를
 * 누르면 목록이 아니라 카카오로 간다. 카카오는 이미 끝난 인가 요청이라
 * 자기 로그인 화면을 다시 띄운다 — 사용자 눈에는 「로그인했는데 또
 * 로그인하라고 한다」 로 보인다 (2026-09-10 신고).
 *
 * 그래서 **한 번만** 뒤로가기를 기록 대신 정해진 자리로 보낸다. 이
 * 표시가 그 한 번을 가리킨다.
 *
 * `sessionStorage` 다. 탭을 닫으면 사라져야 하는 값이고, 다른 탭까지
 * 따라가면 거기서 엉뚱하게 한 번 먹힌다.
 */

const KEY = 'duckmoim.afterAuth'

/** 로그인을 끝내고 원래 화면으로 보내기 직전에 남긴다 */
export function markAfterAuth(): void {
  try {
    sessionStorage.setItem(KEY, '1')
  } catch {
    /* 사파리 프라이빗 등 저장이 막힌 경우. 뒤로가기가 예전처럼 동작할
       뿐이라 로그인 자체를 막을 이유가 없다 */
  }
}

/**
 * 표시를 꺼내면서 지운다.
 *
 * **꺼내는 즉시 지우는 것이 핵심이다.** 안 지우면 그 뒤로 누르는 모든
 * 뒤로가기가 기록을 무시하게 되어, 상세 → 상세로 옮겨 다닌 사람이
 * 두 번째 뒤로가기에서 엉뚱한 데로 간다.
 */
export function takeAfterAuth(): boolean {
  try {
    const v = sessionStorage.getItem(KEY)
    if (v) sessionStorage.removeItem(KEY)
    return v === '1'
  } catch {
    return false
  }
}
