import type { EventItem } from '@/types'

/**
 * 데이터 제공처 표기.
 *
 * ─────────────────────────────────────────────────────────
 * **`sourceUrl` 과 다른 것이다.**
 *
 * 원문 링크는 「이 행사의 안내가 어디 있나」 이고 이건 「이 정보를 누가
 * 주었나」 다. 앞의 것은 방문자를 위한 것이고 이건 제공처와의 약속이다.
 *
 * ─────────────────────────────────────────────────────────
 * **콘서트에만 붙는다.**
 *
 * KOPIS 이용제한이 「출처가 명시되지 않을 경우 서비스가 중단될 수 있음」
 * 이라고 적어 두었다. 생카·팝업은 공개 게시물을 정리한 것이라 이 의무가
 * 없고, 붙이면 오히려 출처를 속이는 것이 된다 (CLAUDE.md 첫 규칙).
 *
 * ─────────────────────────────────────────────────────────
 * **`kind` 로 가른다. `source` 로 가르지 않는다.**
 *
 * `to-events.mjs` 가 찍는 `source: 'KOPIS'` 가 더 정확해 보이지만 그 값은
 * **화면 계약에 없다** — `/api/v1/events` 응답에 그런 칸이 없어서
 * `EventItem` 에도 안 넣었다. 그걸로 가르면 빌드타임 JSON 을 읽을 때는
 * 표기가 뜨고 API 로 받을 때는 조용히 사라진다. 법적 의무가 걸린 줄이
 * 경로에 따라 없어지는 것이 제일 나쁘다.
 *
 * **콘서트를 만드는 수집원이 KOPIS 하나라서** 성립한다 (`to-events.mjs` 의
 * 빌더 셋 중 `kopisToEvent` 만 `CONCERT` 를 찍는다). 콘서트를 주는 소스가
 * 하나 더 생기면 이 함수가 거짓말을 시작하므로, 그때는 계약에 제공처
 * 필드를 넣고 여기를 그 값으로 바꾼다.
 */

/**
 * KOPIS 가 요구하는 문구.
 *
 * **우리가 다듬지 않는다.** 「예술경영지원센터 · KOPIS 제공」 처럼 줄여
 * 적고 싶어지지만, 이용제한이 예시로 든 형태를 그대로 쓰는 편이 나중에
 * 다투지 않는다. 괄호 안 `(재)` 도 그쪽 표기다.
 */
const KOPIS = '출처 : (재)예술경영지원센터 공연예술통합전산망, www.kopis.or.kr'

export default function SourceCredit({ kind }: { kind: EventItem['kind'] }) {
  if (kind !== 'CONCERT') return null
  return <p className="credit">{KOPIS}</p>
}
