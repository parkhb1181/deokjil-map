import { notFound } from 'next/navigation'

/**
 * 와이어프레임과 실서비스를 가르는 스위치.
 *
 * 이 저장소에는 성격이 다른 두 가지가 같이 있다.
 *
 *   실서비스   /  ·  /e/[id]  ·  /a/[subject]
 *              크롤러가 모은 205건이 흐르고 검색 유입을 받는다
 *
 *   와이어프레임  /p · /me · /login · /admin15616 ...
 *              목데이터. 서버도 인증도 없다. 로그인을 눌러도
 *              실제로는 아무 일이 일어나지 않는다
 *
 * 둘이 한 배포에 섞이면 진짜 방문자가 가짜 모집글을 보고 가짜 로그인을
 * 누른다. robots 의 noindex 는 **검색 색인만 막지 접근은 막지 않는다.**
 * 주소를 아는 사람은 그대로 들어온다.
 *
 * 그래서 라우트 자체를 닫는다. 링크만 숨기면 문을 가린 것이지 잠근
 * 것이 아니다.
 *
 * ─────────────────────────────────────────────────────────
 * 켜지는 곳
 *
 *   npm run dev                      항상 켜짐
 *   NEXT_PUBLIC_WIREFRAME=1 로 빌드   켜짐 (팀에 보여줄 미리보기 배포)
 *   그 외 배포                        꺼짐
 *
 * NODE_ENV 하나로만 갈랐더니 미리보기 배포에서도 닫혀서, 팀이 화면을
 * 볼 방법이 로컬뿐이었다. 명시적인 깃발을 따로 둔다.
 *
 * 값이 빌드 시점에 정해지므로, 꺼진 빌드에서는 이 분기와 목데이터가
 * 번들에서 통째로 빠진다.
 */
export const IS_WIREFRAME =
  process.env.NEXT_PUBLIC_WIREFRAME === '1' || process.env.NODE_ENV === 'development'

/**
 * 와이어프레임 화면의 page.tsx 첫 줄에서 부른다.
 *
 * 꺼져 있으면 404 다. 빌드 때 판정되므로 그 화면은 아예 만들어지지
 * 않는다. "준비 중입니다" 같은 안내를 두지 않는 것은, 그것도 화면
 * 하나를 배포하는 일이고 없는 기능을 곧 나올 것처럼 약속하기 때문이다.
 */
export function wireframeOnly(): void {
  if (!IS_WIREFRAME) notFound()
}
